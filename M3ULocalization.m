static NSDictionary *table(int col)
{
    static NSDictionary *en, *ru;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        NSMutableDictionary *e = [NSMutableDictionary dictionary], *r = [NSMutableDictionary dictionary];
        for (size_t i = 0; i < sizeof(kRows) / sizeof(kRows[0]); i++) {
            NSString *pl = [NSString stringWithUTF8String:kRows[i][0]];
            [e setObject:[NSString stringWithUTF8String:kRows[i][1]] forKey:pl];
            [r setObject:[NSString stringWithUTF8String:kRows[i][2]] forKey:pl];
        }
        en = e; ru = r;
    });
    return col == 1 ? en : ru;
}

/* Bez wyboru w ustawieniach: język urządzenia (rosyjski, angielski), inaczej polski. */
NSString *M3UCurrentLanguage(void)
{
    NSString *saved = [[NSUserDefaults standardUserDefaults] stringForKey:kLangKey];
    if ([saved isEqualToString:@"pl"] || [saved isEqualToString:@"en"] || [saved isEqualToString:@"ru"]) return saved;
    NSString *sys = [[NSLocale preferredLanguages] firstObject];
    if ([sys hasPrefix:@"ru"]) return @"ru";
    if ([sys hasPrefix:@"en"]) return @"en";
    return @"pl";
}

void M3USetLanguage(NSString *code)
{
    [[NSUserDefaults standardUserDefaults] setObject:code forKey:kLangKey];
    [[NSUserDefaults standardUserDefaults] synchronize];
    [[NSNotificationCenter defaultCenter] postNotificationName:M3ULanguageDidChange object:nil];
}

NSString *M3ULocalize(NSString *polish)
{
    if (!polish) return nil;
    NSString *lang = M3UCurrentLanguage();
    if ([lang isEqualToString:@"pl"]) return polish;
    NSString *t = [table([lang isEqualToString:@"en"] ? 1 : 2) objectForKey:polish];
    return t ?: polish;
}
